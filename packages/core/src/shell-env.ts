import { execFile } from 'node:child_process';
import { mkdir, rename, writeFile } from 'node:fs/promises';
import { promisify } from 'node:util';
import { rootCertificates } from 'node:tls';
import { join } from 'node:path';
import { placeholderFor } from './placeholders.js';
import type { Credential } from './types.js';

export interface ShellEnvOptions {
  /** Usually ~/.keybroker */
  dir: string;
  proxyUrl: string;
  caCert: string;
  credentials: Credential[];
}

export interface ShellEnvPaths {
  envFile: string;
  caFile: string;
  bundleFile: string;
}

const shellQuote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

export function renderEnvFile(opts: ShellEnvOptions, paths: ShellEnvPaths): string {
  const lines = [
    '# Generated by Keybroker. Source this in an agent shell to route API calls through the broker.',
    `export HTTPS_PROXY=${shellQuote(opts.proxyUrl)}`,
    `export https_proxy=${shellQuote(opts.proxyUrl)}`,
    `export HTTP_PROXY=${shellQuote(opts.proxyUrl)}`,
    `export http_proxy=${shellQuote(opts.proxyUrl)}`,
    `export NO_PROXY='localhost,127.0.0.1,::1'`,
    `export no_proxy='localhost,127.0.0.1,::1'`,
    '# Node fetch only honours *_PROXY with this set (Node 24+).',
    `export NODE_USE_ENV_PROXY=1`,
    '# NODE_EXTRA_CA_CERTS is additive; the others replace the trust store, so they get the full bundle.',
    `export NODE_EXTRA_CA_CERTS=${shellQuote(paths.caFile)}`,
    `export SSL_CERT_FILE=${shellQuote(paths.bundleFile)}`,
    `export REQUESTS_CA_BUNDLE=${shellQuote(paths.bundleFile)}`,
    `export CURL_CA_BUNDLE=${shellQuote(paths.bundleFile)}`,
    `export KEYBROKER_PROXY=${shellQuote(opts.proxyUrl)}`,
    '',
    '# Placeholders: SDKs need a non-empty key; the proxy swaps in the real one.',
    ...opts.credentials
      .filter((c) => c.envVar)
      .map((c) => `export ${c.envVar}=${shellQuote(placeholderFor(c.name))}`),
    '',
  ];
  return lines.join('\n');
}

async function atomicWrite(path: string, contents: string) {
  const tmp = `${path}.tmp`;
  await writeFile(tmp, contents, { mode: 0o644 });
  await rename(tmp, path);
}

/**
 * Certificates this Mac trusts beyond Node's built-in list (e.g. a company root an admin
 * installed). SSL_CERT_FILE replaces a tool's trust store, so without these, tools that
 * worked before Keybroker could start failing TLS checks.
 */
async function macKeychainCerts(): Promise<string[]> {
  if (process.platform !== 'darwin') return [];
  try {
    const { stdout } = await promisify(execFile)(
      '/usr/bin/security',
      ['find-certificate', '-a', '-p', '/System/Library/Keychains/SystemRootCertificates.keychain', '/Library/Keychains/System.keychain'],
      { maxBuffer: 16 * 1024 * 1024 },
    );
    return stdout.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g) ?? [];
  } catch {
    return [];
  }
}

/** Write env.sh, the CA cert and a CA bundle (system roots + this Mac's + ours) into `dir`. */
export async function writeShellEnv(opts: ShellEnvOptions): Promise<ShellEnvPaths> {
  await mkdir(opts.dir, { recursive: true });
  const paths: ShellEnvPaths = {
    envFile: join(opts.dir, 'env.sh'),
    caFile: join(opts.dir, 'ca.pem'),
    bundleFile: join(opts.dir, 'ca-bundle.pem'),
  };
  await atomicWrite(paths.caFile, opts.caCert);
  const certs = new Set([...rootCertificates, ...(await macKeychainCerts())]);
  await atomicWrite(paths.bundleFile, [...certs, opts.caCert].join('\n'));
  await atomicWrite(paths.envFile, renderEnvFile(opts, paths));
  return paths;
}
